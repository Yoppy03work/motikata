const HOLIDAY_SET = new Set(HOLIDAYS);

// 対応年の範囲を実データから自動算出。リスト末尾を伸ばせば自動的に拡張される。
const SUPPORTED_YEARS = (() => {
  const years = HOLIDAYS.map((d) => Number(d.slice(0, 4)));
  return { min: Math.min(...years), max: Math.max(...years) };
})();

export class HolidayYearOutOfRangeError extends Error {
  constructor(year: number, range: { min: number; max: number }) {
    super(
      `${year}年は祝日テーブルの対応範囲(${range.min}-${range.max})外です。` +
        `src/lib/japaneseHolidays.ts に追記してください。`,
    );
    this.name = "HolidayYearOutOfRangeError";
  }
}

/** JST の yyyy-MM-dd 形式で渡して、その日が日本の国民の祝日(振替含む)か。
 *  対応年外の日付には HolidayYearOutOfRangeError を throw する。
 *  これは「黙って通常授業日と判定する」誤動作を避けるための明示エラー。 */
export function isJapaneseHoliday(jstYmd: string): boolean {
  const y = Number(jstYmd.slice(0, 4));
  if (!Number.isFinite(y) || y < SUPPORTED_YEARS.min || y > SUPPORTED_YEARS.max) {
    throw new HolidayYearOutOfRangeError(y, SUPPORTED_YEARS);
  }
  return HOLIDAY_SET.has(jstYmd);
}

/** "対応範囲内か" を非破壊で問い合わせるヘルパー。
 *  呼び出し側で「対応外ならスキップして通常授業日扱い」など、
 *  throw とは別の挙動を選びたい場合に使う。 */
export function isHolidayYearSupported(year: number): boolean {
  return (
    Number.isFinite(year) &&
    year >= SUPPORTED_YEARS.min &&
    year <= SUPPORTED_YEARS.max
  );
}

export const HOLIDAY_YEAR_RANGE = SUPPORTED_YEARS;
